"""What is in scope, how it splits into projects, how many lines each holds.

The rules are the ones `references/inventory.md` states. Ownership of a tool is decided
beside that tool, in the language modules; this module supplies the readers they share.
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import stat
import subprocess
import tomllib
from dataclasses import dataclass, field, fields
from functools import cache
from pathlib import Path

SKIP_DIRS = frozenset(
    ("node_modules", "vendor", "dist", "build", "bin", "obj", ".venv", "venv", "__pycache__", "coverage")
)
WORKFLOW_ROOTS = (".github/", ".gitea/", ".forgejo/")

LANGUAGES = {
    "js-ts": (".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs"),
    "python": (".py", ".pyi"),
    "csharp": (".cs",),
    "go": (".go",),
    "c-cpp": (".c", ".h", ".cpp", ".cc", ".cxx", ".c++", ".hpp", ".hh", ".hxx", ".h++"),
}
ASSETS = {"css": (".css",), "graphql": (".graphql", ".gql")}
C_SOURCES = (".c", ".cpp", ".cc", ".cxx", ".c++")
C_HEADERS = (".h", ".hpp", ".hh", ".hxx", ".h++")

MANIFEST_NAMES = frozenset(("package.json", "pyproject.toml", "go.mod", "configure.ac", "BUILD.bazel", "BUILD"))
MANIFEST_SUFFIXES = (".csproj", ".sln", ".vcxproj")
PROJECT_CALL = re.compile(rb"^\s*project\s*\(", re.I | re.M)

SNAPSHOT_NAMES = frozenset(("captured", "golden", "__snapshots__", "fixtures", "testdata", "snapshots"))
LOCKFILES = frozenset(
    (
        "package-lock.json",
        "npm-shrinkwrap.json",
        "pnpm-lock.yaml",
        "yarn.lock",
        "bun.lock",
        "bun.lockb",
        "uv.lock",
        "poetry.lock",
        "pdm.lock",
        "Pipfile.lock",
        "go.sum",
        "packages.lock.json",
        "conan.lock",
        "Cargo.lock",
        "composer.lock",
        "Gemfile.lock",
    )
)
GENERATED_DIRS = frozenset(("gen", "generated", "__generated__"))
GENERATED_NAME = re.compile(r"\.(gen|generated|pb|g)\.[A-Za-z0-9+]+$|_pb2(_grpc)?\.pyi?$|\.pb\.go$|_gen\.go$|\.min\.(js|css)$")
GENERATED_HEADER = re.compile(rb"code generated .{0,80}do not edit|@generated|<auto-generated", re.I)


def ext_of(path: str) -> str:
    return os.path.splitext(path)[1].lower()


def language_of(path: str) -> str | None:
    ext = ext_of(path)
    for lang, exts in LANGUAGES.items():
        if ext in exts:
            return lang
    return None


def asset_of(path: str) -> str | None:
    ext = ext_of(path)
    for kind, exts in ASSETS.items():
        if ext in exts:
            return kind
    return None


def in_scope(rel: str) -> bool:
    dirs = rel.split("/")[:-1]
    if rel.startswith(WORKFLOW_ROOTS):
        dirs = dirs[1:]
    return not any(d in SKIP_DIRS or d.startswith(".") for d in dirs)


def git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True)


def is_git_repo(repo: Path) -> bool:
    return git(repo, "rev-parse", "--is-inside-work-tree").returncode == 0


def list_files(repo: Path) -> list[str]:
    """Tracked files plus untracked-unignored ones, as paths relative to `repo`."""
    done = git(repo, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    if done.returncode == 0:
        names = [n for n in done.stdout.decode("utf-8", "surrogateescape").split("\0") if n]
    else:
        names = _walk_files(repo)
    return [name for name in sorted(set(names)) if in_scope(name) and _is_regular(repo / name)]


def _walk_files(repo: Path) -> list[str]:
    names = []
    for base, dirs, files in os.walk(repo):
        dirs[:] = [d for d in dirs if d != ".git"]
        rel = os.path.relpath(base, repo)
        names += [f if rel == "." else f"{rel}/{f}".replace(os.sep, "/") for f in files]
    return names


def _is_regular(path: Path) -> bool:
    try:
        return stat.S_ISREG(os.lstat(path).st_mode)
    except OSError:
        return False


def count_lines(path: Path) -> int:
    """`wc -l`: newline bytes, blank and comment lines included."""
    total = 0
    try:
        with open(path, "rb") as fh:
            while chunk := fh.read(1 << 20):
                total += chunk.count(b"\n")
    except OSError:
        pass
    return total


def looks_generated(repo: Path, rel: str) -> bool:
    parts = rel.split("/")
    if any(p in GENERATED_DIRS for p in parts[:-1]) or GENERATED_NAME.search(parts[-1]):
        return True
    try:
        with open(repo / rel, "rb") as fh:
            return bool(GENERATED_HEADER.search(fh.read(1024)))
    except OSError:
        return False


TEST_PATH = re.compile(
    r"(^|/)(tests?|__tests__|spec|specs|e2e|testing)/"
    r"|(^|/)(test_[^/]+|[^/]+_test|conftest)\.pyi?$"
    r"|_test\.go$"
    r"|\.(test|spec|stories)\.[cm]?[jt]sx?$"
    r"|Tests?\.cs$"
    r"|(^|/)[^/]*[_.-]tests?\.(c|cc|cpp|cxx)$"
)


def is_test_path(rel: str) -> bool:
    return bool(TEST_PATH.search(rel))


def under_snapshot(rel: str) -> bool:
    return any(p in SNAPSHOT_NAMES for p in rel.split("/")[:-1])


def parent(rel_dir: str) -> str:
    return os.path.dirname(rel_dir) or "."


def ancestry(rel_dir: str):
    """`rel_dir`, then each directory above it, ending at the repo root `.`."""
    here = rel_dir or "."
    while True:
        yield here
        if here == ".":
            return
        here = parent(here)


def is_within(rel: str, rel_dir: str) -> bool:
    return rel_dir == "." or rel == rel_dir or rel.startswith(rel_dir + "/")


@cache
def _listdir(path: str) -> tuple[str, ...]:
    try:
        return tuple(sorted(os.listdir(path)))
    except OSError:
        return ()


def find_config(repo: Path, rel_dir: str, patterns, *, local: bool = False) -> str | None:
    """First file or directory matching `patterns` in `rel_dir` or an ancestor, repo-relative."""
    for here in ancestry(rel_dir):
        name = _first_match(_listdir(str(repo / here)), patterns)
        if name is not None:
            return name if here == "." else f"{here}/{name}"
        if local:
            return None
    return None


def _first_match(names: tuple[str, ...], patterns) -> str | None:
    """The first name the earliest pattern matches: pattern order outranks name order."""
    for pattern in patterns:
        for name in names:
            if fnmatch.fnmatchcase(name, pattern):
                return name
    return None


@cache
def read_json(path: str):
    try:
        with open(path, encoding="utf-8-sig") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


@cache
def read_jsonc(path: str):
    """JSON with `//` and `/* */` comments and trailing commas, as tsconfig and Biome allow."""
    try:
        with open(path, encoding="utf-8-sig") as fh:
            text = fh.read()
    except OSError:
        return None
    cleaned = re.sub(r",(\s*[}\]])", r"\1", _strip_comments(text))
    try:
        return json.loads(cleaned)
    except ValueError:
        return None


def _strip_comments(text: str) -> str:
    out, i = [], 0
    while i < len(text):
        if text[i] == '"':
            end = _string_end(text, i)
            out.append(text[i:end])
            i = end
        elif text.startswith("//", i):
            i = text.find("\n", i)
            if i < 0:
                break
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = len(text) if end < 0 else end + 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def _string_end(text: str, start: int) -> int:
    """The index just past the string literal that opens at `start`, or the end of `text`."""
    i = start + 1
    while i < len(text):
        if text[i] == "\\":
            i += 2
        elif text[i] == '"':
            return i + 1
        else:
            i += 1
    return len(text)


@cache
def read_toml(path: str):
    try:
        with open(path, "rb") as fh:
            return tomllib.load(fh)
    except (OSError, ValueError):
        return None


DEP_BLOCKS = ("dependencies", "devDependencies", "optionalDependencies", "peerDependencies")


def npm_dependency(repo: Path, rel_dir: str, *names: str) -> str | None:
    """`<package.json> (<block>)` when a dependency block in `rel_dir` or an ancestor names
    the package. A `scripts` entry never decides ownership, so the manifest is read as JSON."""
    for here in ancestry(rel_dir):
        manifest = read_json(str(repo / here / "package.json"))
        block = _dependency_block(manifest, names) if isinstance(manifest, dict) else None
        if block is not None:
            where = "package.json" if here == "." else f"{here}/package.json"
            return f"{where} {block}"
    return None


def _dependency_block(manifest: dict, names) -> str | None:
    for block in DEP_BLOCKS:
        deps = manifest.get(block)
        if isinstance(deps, dict) and any(name in deps for name in names):
            return block
    return None


def npm_manifest_key(repo: Path, rel_dir: str, key: str) -> str | None:
    """A config a tool reads from a top-level `package.json` key (`prettier`, `knip`, …)."""
    for here in ancestry(rel_dir):
        manifest = read_json(str(repo / here / "package.json"))
        if isinstance(manifest, dict) and key in manifest:
            where = "package.json" if here == "." else f"{here}/package.json"
            return f'{where} "{key}"'
    return None


REQUIREMENT_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def _normal(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirement_names(entries) -> set[str]:
    found = set()
    for entry in entries or ():
        if isinstance(entry, str) and (m := REQUIREMENT_NAME.match(entry)):
            found.add(_normal(m.group(1)))
    return found


def _pyproject_dependencies(doc: dict) -> dict[str, set[str]]:
    """Declared packages by the table that declares them, covering PEP 621, PEP 735,
    poetry, pdm and uv's legacy dev list."""
    out: dict[str, set[str]] = {}
    for label, names in _dependency_tables(doc):
        if names:
            out.setdefault(label, set()).update(names)
    return out


def _dependency_tables(doc: dict):
    """(label, normalized names) per table, in the order a lookup reports the first match."""
    project = doc.get("project") or {}
    yield "project.dependencies", _requirement_names(project.get("dependencies"))
    for extra, entries in (project.get("optional-dependencies") or {}).items():
        yield f"project.optional-dependencies.{extra}", _requirement_names(entries)
    for group, entries in (doc.get("dependency-groups") or {}).items():
        yield f"dependency-groups.{group}", _requirement_names(entries)
    tool = doc.get("tool") or {}
    poetry = tool.get("poetry") or {}
    for key in ("dependencies", "dev-dependencies"):
        yield f"tool.poetry.{key}", {_normal(n) for n in (poetry.get(key) or {})}
    for group, body in (poetry.get("group") or {}).items():
        yield f"tool.poetry.group.{group}", {_normal(n) for n in ((body or {}).get("dependencies") or {})}
    for group, entries in ((tool.get("pdm") or {}).get("dev-dependencies") or {}).items():
        yield f"tool.pdm.dev-dependencies.{group}", _requirement_names(entries)
    yield "tool.uv.dev-dependencies", _requirement_names((tool.get("uv") or {}).get("dev-dependencies"))


def python_tool_table(repo: Path, rel_dir: str, name: str) -> str | None:
    for here in ancestry(rel_dir):
        doc = read_toml(str(repo / here / "pyproject.toml"))
        if isinstance(doc, dict) and name in (doc.get("tool") or {}):
            where = "pyproject.toml" if here == "." else f"{here}/pyproject.toml"
            return f"{where} [tool.{name}]"
    return None


def python_dependency(repo: Path, rel_dir: str, name: str) -> str | None:
    want = _normal(name)
    for here in ancestry(rel_dir):
        prefix = "" if here == "." else f"{here}/"
        doc = read_toml(str(repo / here / "pyproject.toml"))
        label = _pyproject_label(doc, want) if isinstance(doc, dict) else None
        if label is not None:
            return f"{prefix}pyproject.toml {label}"
        entry = _requirements_naming(repo / here, want)
        if entry is not None:
            return f"{prefix}{entry}"
    return None


def _pyproject_label(doc: dict, want: str) -> str | None:
    return next((label for label, names in _pyproject_dependencies(doc).items() if want in names), None)


def _requirements_naming(folder: Path, want: str) -> str | None:
    """The first `requirements*.txt` in `folder` that lists the normalized package `want`."""
    for entry in _listdir(str(folder)):
        if not fnmatch.fnmatchcase(entry, "requirements*.txt"):
            continue
        try:
            lines = (folder / entry).read_text(errors="replace").splitlines()
        except OSError:
            continue
        if want in _requirement_names(l for l in lines if not l.lstrip().startswith(("#", "-"))):
            return entry
    return None


def slug(dir: str) -> str:
    return "root" if dir == "." else dir.replace("/", "-")


@dataclass(frozen=True)
class ProjectRecord:
    """A project as `results.json` keeps it: file counts, not file lists."""

    dir: str
    manifests: list[str] = field(default_factory=list)
    files: dict[str, int] = field(default_factory=dict)
    lines: dict[str, int] = field(default_factory=dict)
    asset_lines: dict[str, int] = field(default_factory=dict)
    owned: dict[str, str] = field(default_factory=dict)
    unowned: list[str] = field(default_factory=list)
    facts: dict[str, str] = field(default_factory=dict)
    fixture_only: dict[str, str] = field(default_factory=dict)

    @property
    def slug(self) -> str:
        return slug(self.dir)

    def to_json(self) -> dict:
        return {f.name: getattr(self, f.name) for f in fields(self)}

    @classmethod
    def from_json(cls, doc: dict) -> ProjectRecord:
        return cls(**{f.name: doc[f.name] for f in fields(cls)})


@dataclass
class Project:
    dir: str
    manifests: list[str] = field(default_factory=list)
    files: dict[str, list[str]] = field(default_factory=dict)
    lines: dict[str, int] = field(default_factory=dict)
    assets: dict[str, list[str]] = field(default_factory=dict)
    asset_lines: dict[str, int] = field(default_factory=dict)
    every_file: list[str] = field(default_factory=list)
    owned: dict[str, str] = field(default_factory=dict)
    unowned: list[str] = field(default_factory=list)
    facts: dict[str, str] = field(default_factory=dict)
    fixture_only: dict[str, str] = field(default_factory=dict)

    @property
    def shell(self) -> bool:
        return not self.files

    @property
    def slug(self) -> str:
        return slug(self.dir)

    def record(self) -> ProjectRecord:
        return ProjectRecord(
            dir=self.dir,
            manifests=list(self.manifests),
            files={lang: len(paths) for lang, paths in self.files.items()},
            lines=dict(self.lines),
            asset_lines=dict(self.asset_lines),
            owned=dict(self.owned),
            unowned=list(self.unowned),
            facts=dict(self.facts),
            fixture_only=dict(self.fixture_only),
        )

    def kloc(self, language: str) -> float:
        return self.lines.get(language, 0) / 1000

    def rel(self, path: str) -> str:
        """`path` (repo-relative) as seen from the project directory."""
        return path if self.dir == "." else os.path.relpath(path, self.dir)


@dataclass
class Inventory:
    repo: Path
    head: str
    dirty: int
    is_git: bool
    files: list[str]
    line_counts: dict[str, int]
    projects: list[Project]
    selected: list[str]
    workflows: list[str]
    snapshots: list[str]
    generated: list[str]
    lockfiles: list[str]
    unassessed: dict[str, int]

    def project(self, rel_dir: str) -> Project | None:
        return next((p for p in self.projects if p.dir == rel_dir), None)

    def scanned(self) -> list[Project]:
        return [p for p in self.projects if not p.shell]

    def scan_dirs(self) -> list[str]:
        """Directories the repo-wide tools cover: the repo, or the selected projects."""
        return self.selected or ["."]

    def in_selection(self, rel: str) -> bool:
        return not self.selected or any(is_within(rel, d) for d in self.selected)


def _is_project_marker(repo: Path, rel: str, siblings: set[str]) -> bool:
    name = rel.rsplit("/", 1)[-1]
    if name in MANIFEST_NAMES or name.endswith(MANIFEST_SUFFIXES):
        return True
    if name in ("CMakeLists.txt", "meson.build"):
        try:
            return bool(PROJECT_CALL.search((repo / rel).read_bytes()))
        except OSError:
            return False
    if name in ("Makefile", "makefile", "GNUmakefile"):
        return any(ext_of(s) in C_SOURCES + C_HEADERS for s in siblings)
    return False


def _workflow_files(files: list[str]) -> list[str]:
    out = []
    for rel in files:
        name = rel.rsplit("/", 1)[-1]
        if rel.startswith(tuple(root + "workflows/" for root in WORKFLOW_ROOTS)) and name.endswith((".yml", ".yaml")):
            out.append(rel)
        elif name in ("action.yml", "action.yaml"):
            out.append(rel)
    return out


def build(repo: Path, selected: list[str]) -> Inventory:
    repo = repo.resolve()
    is_git = is_git_repo(repo)
    files = list_files(repo)
    marker_dirs = _marker_dirs(repo, files)
    ordered = sorted(marker_dirs, key=lambda d: (d == ".", -len(d), d))  # the root matches last

    projects = {d: Project(dir=d, manifests=sorted(m)) for d, m in marker_dirs.items()}
    line_counts: dict[str, int] = {}
    unassessed: dict[str, int] = {}
    for rel in files:
        owner = projects[next(d for d in ordered if is_within(rel, d))]
        _add_file(repo, rel, owner, line_counts, unassessed)

    for project in projects.values():
        _mark_fixture_only(project)

    wanted = sorted({(s.strip("/") or ".") for s in selected})
    head = git(repo, "rev-parse", "--short", "HEAD").stdout.decode().strip() if is_git else ""
    dirty = len(footprint(repo).splitlines()) if is_git else 0
    listed = [p for p in sorted(projects.values(), key=lambda p: p.dir) if p.every_file or p.manifests]
    return Inventory(
        repo=repo,
        head=head or "none",
        dirty=dirty,
        is_git=is_git,
        files=files,
        line_counts=line_counts,
        projects=[p for p in listed if not wanted or p.dir in wanted],
        selected=wanted,
        workflows=_workflow_files(files),
        snapshots=sorted({"/".join(f.split("/")[: _snapshot_depth(f)]) + "/" for f in files if under_snapshot(f)}),
        generated=[f for f in files if (language_of(f) or asset_of(f)) and looks_generated(repo, f)],
        lockfiles=[f for f in files if f.rsplit("/", 1)[-1] in LOCKFILES],
        unassessed=unassessed,
    )


def _marker_dirs(repo: Path, files: list[str]) -> dict[str, list[str]]:
    """Each directory holding a project marker, with its markers; the root is always one."""
    by_dir: dict[str, set[str]] = {}
    for rel in files:
        by_dir.setdefault(parent(rel), set()).add(rel.rsplit("/", 1)[-1])
    marker_dirs: dict[str, list[str]] = {}
    for rel in files:
        here = parent(rel)
        if _is_project_marker(repo, rel, by_dir[here]):
            marker_dirs.setdefault(here, []).append(rel)
    marker_dirs.setdefault(".", [])
    return marker_dirs


def _add_file(repo: Path, rel: str, owner: Project, line_counts: dict[str, int], unassessed: dict[str, int]) -> None:
    owner.every_file.append(rel)
    lang, asset = language_of(rel), asset_of(rel)
    if lang:
        n = line_counts[rel] = count_lines(repo / rel)
        owner.files.setdefault(lang, []).append(rel)
        owner.lines[lang] = owner.lines.get(lang, 0) + n
    elif asset:
        n = line_counts[rel] = count_lines(repo / rel)
        owner.assets.setdefault(asset, []).append(rel)
        owner.asset_lines[asset] = owner.asset_lines.get(asset, 0) + n
    else:
        ext = ext_of(rel).lstrip(".") or "(none)"
        unassessed[ext] = unassessed.get(ext, 0) + 1


def _mark_fixture_only(project: Project) -> None:
    for lang, paths in project.files.items():
        if all(under_snapshot(p) for p in paths):
            roots = sorted({"/".join(p.split("/")[: _snapshot_depth(p)]) for p in paths})
            project.fixture_only[lang] = ", ".join(roots)


def _snapshot_depth(rel: str) -> int:
    parts = rel.split("/")[:-1]
    return next(i for i, p in enumerate(parts) if p in SNAPSHOT_NAMES) + 1


def footprint(repo: Path) -> str:
    """The repo's dirty state; `health.py finish` compares a second listing against the first."""
    done = git(repo, "status", "--porcelain", "--untracked-files=all", "--ignored=no")
    lines = done.stdout.decode("utf-8", "surrogateescape").splitlines()
    return "".join(line + "\n" for line in sorted(lines))
